assert len(FONT5) == 64 * 5
h.append(arr('FONT5', 'uint8_t', FONT5, 15))
# a preview of the font, to check by eye
img = Image.new('L', (64 * 6 + 2, 9), 255)
for c in range(64):
    for x in range(5):
        col = FONT5[c * 5 + x]
        for y in range(7):
            if col >> y & 1: img.putpixel((1 + c * 6 + x, 1 + y), 0)
prev = OUT.parent.parent.parent / 'build' / 'font5.png'
prev.parent.mkdir(parents=True, exist_ok=True)
