"""Function Acid: generate firmware/src/acid_tables.h (all the tables the chip must not compute: no FPU).
   python tools/gen_acid_tables.py            (needs Pillow for the small font)
Tables: e^-x (Q15), a sine (Q15), phase steps per 1/64 semitone at 44.1 kHz, the animals' wavetables
(harmonic amplitudes measured from real recordings, see visual-interaction-lab/04-function-acid), a 5x7 font."""
import math, pathlib, sys

FS = 44100
OUT = pathlib.Path(__file__).resolve().parent.parent / 'firmware' / 'src' / 'acid_tables.h'

def arr(name, ctype, vals, per=12):
    rows = [', '.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f'static const {ctype} {name}[{len(vals)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'

h = ['/* SPDX-License-Identifier: GPL-3.0-only */',
     '/* Function Acid tables: generated by tools/gen_acid_tables.py, do not edit. */', '']
h.append(arr('EXPT', 'int16_t', [round(32767 * math.exp(-i / 32)) for i in range(257)]))
h.append(arr('SINT', 'int16_t', [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1024)]))
# phase step for MIDI 120 + r/64 (r = 0..767) at 44.1 kHz; lower octaves shift right
h.append(arr('INC64', 'uint32_t', [round(4294967296 * 440 * 2 ** ((120 + r / 64 - 69) / 12) / FS) for r in range(768)], 8))

DB = lambda a: [10 ** (d / 20) for d in a]
ANIMALS = [  # name, centre (MIDI), harmonics (dB) — from function-sounds/concert/analysis/report.md
    ('FLY', 56.4, DB([0, -5, -9, -12, -11, -16, -20, -22, -24, -26])),
    ('BEE', 59.1, DB([-4.6, 0, -0.5, -0.2, -6, -3, -6, -18.7, -22.3, -28.1])),
    ('FROG', 54.0, DB([-24, 0, -3.5, -7.3, -9.4, -15.9, -13.5, -11.5, -12.9, -8.9, -9.2, -11])),
    ('WHALE', 24.2, DB([-19, 0, -7, -10, -17, -13, -3, -12, -15, -18])),
]
wts = []
for _, _, harm in ANIMALS:
    t = [sum(hk * math.sin(2 * math.pi * (k + 1) * i / 256) for k, hk in enumerate(harm)) for i in range(256)]
    pk = max(abs(v) for v in t)
    wts += [round(v / pk * 30000) for v in t]
h.append(arr('BIO_WT', 'int16_t', wts))
h.append(arr('BIO_CENTER_Q8', 'int32_t', [round(c * 256) for _, c, _ in ANIMALS]))
h.append(arr('BIO_OCT', 'int32_t', [round((c - 60) / 12) * 12 for _, c, _ in ANIMALS]))
# harmonic amplitudes Q8 (for the spectrum dots on the screen)
h.append(arr('BIO_HARM', 'uint8_t', [min(255, round(255 * (harm[k] if k < len(harm) else 0) / max(harm))) for _, _, harm in ANIMALS for k in range(12)]))

