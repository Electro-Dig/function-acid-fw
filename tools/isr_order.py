"""FN ACID 0.51: the code the audio and timer interrupts reach, first in flash.

The FM-1 runs code from flash through a 32 KB instruction cache. Where a function lands decides which others it
shares cache lines with: JIANT 0.9.10 added 6 KB of screen code, the audio code moved by 6 KB and the load went from
fine to 94 % (its README, 0.9.10-0.9.12). So the functions the interrupts reach are linked first, in the order they
are reached, and screen work can no longer move them.

    python3 tools/isr_order.py build/dinghy.dis build/isr_order.ld

reads the disassembly (objdump -d), walks the calls and tail jumps from the interrupt entries, and writes one
*(.text.NAME) line per function (each function is its own section: -ffunction-sections). Prints whether it changed.
"""
import re
import sys
from pathlib import Path

ROOTS = ["isr_alnk0", "isr_timer5", "fm1_alnk0_irq", "fm1_timer5_irq"]
LABEL = re.compile(r"^([A-Za-z_][\w.$]*):\s*$")
JUMP = re.compile(r"\b(call|goto)\s+-?\d+\s+<([A-Za-z_][\w.$]*)(\+0x[0-9A-Fa-f]+)?\s*:")


def graph(dis):
    edges, cur = {}, None
    for ln in dis.splitlines():
        m = LABEL.match(ln)
        if m:
            cur = m.group(1)
            edges.setdefault(cur, [])
            continue
        if cur is None:
            continue
        j = JUMP.search(ln)
        if j and j.group(2) != cur and (j.group(1) == "call" or not j.group(3)):   # a call, or a tail jump to a function's start
            if j.group(2) not in edges[cur]:
                edges[cur].append(j.group(2))
    return edges


def reach(edges):
    seen, order, todo = set(), [], [r for r in ROOTS if r in edges]
    while todo:                                 # breadth first: the entries, then what they call, ...
        f = todo.pop(0)
        if f in seen:
            continue
        seen.add(f)
        order.append(f)
        todo.extend(g for g in edges.get(f, []) if g not in seen)
    return order


def main():
    dis, out = Path(sys.argv[1]), Path(sys.argv[2])
    order = reach(graph(dis.read_text(errors="replace")))
    text = "/* generated by tools/isr_order.py: the code the interrupts reach, first */\n" + \
        "".join(f"*(.text.{f})\n" for f in order)
    old = out.read_text() if out.exists() else ""
    if text != old:
        out.write_text(text)
    print(f"isr_order: {len(order)} functions{' (changed)' if text != old else ''}")
    return 1 if text != old else 0


if __name__ == "__main__":
    sys.exit(main())
